// data-pdf-chart) and embedded as images.
//
// Everything runs in the browser: no server, no holdings ever leave the device.
//
// Usage (async):
//   await generatePortfolioPdf(analysis, positions, "en");
// ─────────────────────────────────────────────────────────────────────────────

